import type { Question } from "./schema";
import data from "./catalog.generated.json";

/** Answer-free metadata for a published question (safe to bundle into the browser). */
export interface CatalogEntry {
  id: string;
  subject: Question["subject"];
  topic: string;
  subtopic: string;
  type: Question["type"];
  difficulty: Question["difficulty"];
  title: string;
  stem: string;
  estimatedTimeSeconds: number;
  relatedLessonIds: string[];
  smeReview: Question["status"]["smeReview"];
}

export function toCatalog(questions: Question[]): CatalogEntry[] {
  return questions
    .filter((q) => q.status.publication === "published" && q.status.validation === "verified")
    .map((q) => ({
      id: q.id,
      subject: q.subject,
      topic: q.topic,
      subtopic: q.subtopic,
      type: q.type,
      difficulty: q.difficulty,
      title: q.title,
      stem: q.stem,
      estimatedTimeSeconds: q.estimatedTimeSeconds,
      relatedLessonIds: q.relatedLessonIds,
      smeReview: q.status.smeReview,
    }))
    .sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));
}

/** Snapshot generated by `npm run qbank:catalog` from the published bank. */
export const catalog = data as CatalogEntry[];
const byId = new Map(catalog.map((c) => [c.id, c]));
export const getCatalogEntry = (id: string) => byId.get(id);
